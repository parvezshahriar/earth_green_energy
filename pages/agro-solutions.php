      (function initAgroAnimations() {
        const fullText = "Agro Product Solutions: Building a Smarter, Efficient & Future-Proof Agro Industry in Bangladesh";
        const highlight = "Future-Proof Agro Industry";
        const target = document.getElementById('agro-typing-text');
        const cursor = document.getElementById('agro-typing-cursor');

        if (target) {
          target.innerHTML = '';
          let index = 0;
          const speed = 30;

          function typeNextChar() {
            if (index <= fullText.length) {
              const currentSub = fullText.substring(0, index);
              if (currentSub.includes(highlight)) {
                const parts = currentSub.split(highlight);
                target.innerHTML = parts[0] + '<span class="text-primary">' + highlight + '</span>' + (parts[1] || '');
              } else {
                target.textContent = currentSub;
              }
              index++;
              setTimeout(typeNextChar, speed);
            } else {
              target.innerHTML = 'Agro Product Solutions: Building a Smarter, Efficient & <span class="text-primary">Future-Proof Agro Industry</span> in Bangladesh';
              if (cursor) cursor.style.display = 'none';
            }
          }

          setTimeout(typeNextChar, 150);
        }

        // Stats Counter Animation
        const counters = document.querySelectorAll('.agro-counter');
        if (counters.length > 0) {
          function animateCounter(el) {
            if (el.dataset.counted === 'true') return;
            el.dataset.counted = 'true';

            const targetVal = parseFloat(el.getAttribute('data-target') || '0');
            const suffix = el.getAttribute('data-suffix') || '';
            const decimals = parseInt(el.getAttribute('data-decimals') || '0', 10);
            const duration = 1500;
            const startTime = performance.now();

            function updateCount(currentTime) {
              const elapsed = currentTime - startTime;
              const progress = Math.min(elapsed / duration, 1);
              const easeProgress = 1 - Math.pow(1 - progress, 3);
              const currentVal = (targetVal * easeProgress).toFixed(decimals);
              el.textContent = currentVal + suffix;

              if (progress < 1) {
                requestAnimationFrame(updateCount);
              } else {
                el.textContent = (decimals > 0 ? targetVal.toFixed(decimals) : targetVal) + suffix;
              }
            }

            requestAnimationFrame(updateCount);
          }

          if ('IntersectionObserver' in window) {
            const observer = new IntersectionObserver((entries, obs) => {
              entries.forEach(entry => {
                if (entry.isIntersecting) {
                  animateCounter(entry.target);
                  obs.unobserve(entry.target);
                }
              });
            }, { threshold: 0.1 });

            counters.forEach(c => observer.observe(c));
          } else {
            counters.forEach(c => animateCounter(c));
          }
        }
      })();
    </script>

